std::uint8_t glyph_row(int character, int row) {
  if (row < 0 || row >= kGlyphHeight) {
    return 0;
  }
  const int index = character - kGlyphFirst;
  constexpr int kCount = static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));
  if (index < 0 || index >= kCount) {
    return 0;
  }
  return kGlyphs[index][row];
}

TextAtlas build_text_atlas() {
  constexpr int kColumns = 16;
  constexpr int kRows = 6;
  TextAtlas atlas;
  atlas.columns = kColumns;
  atlas.width = kColumns * kGlyphWidth;
  atlas.height = kRows * kGlyphHeight;
  atlas.pixels.assign(
      static_cast<std::size_t>(atlas.width) * static_cast<std::size_t>(atlas.height), 0);

  for (int character = kGlyphFirst; character <= kGlyphLast; ++character) {
    const int index = character - kGlyphFirst;
    const int cell_x = (index % kColumns) * kGlyphWidth;
    const int cell_y = (index / kColumns) * kGlyphHeight;
    for (int row = 0; row < kGlyphHeight; ++row) {
      const std::uint8_t bits = glyph_row(character, row);
      for (int column = 0; column < kGlyphWidth; ++column) {
        const bool on = (bits & (1u << (kGlyphWidth - 1 - column))) != 0u;
        const int x = cell_x + column;
        const int y = cell_y + row;
        atlas.pixels[static_cast<std::size_t>(y) * static_cast<std::size_t>(atlas.width) +
                     static_cast<std::size_t>(x)] = on ? 255u : 0u;
      }
    }
  }
  return atlas;
}

